// Writes src/mdi-names.js: the names of the Material Design Icons (as Home Assistant writes them without "mdi:")
// and their aliases, for the icon search of the editor. Names only: Home Assistant draws the icons (ha-icon).
// Run after an update of @mdi/svg: npm run icons
import { readFileSync, writeFileSync } from 'node:fs';

const read = (path) => JSON.parse(readFileSync(new URL(`../node_modules/@mdi/svg/${path}`, import.meta.url)));
const { version } = read('package.json');
// "name" or "name:alias,alias", one per icon, deprecated ones left out
const icons = read('meta.json')
  .filter((i) => !i.deprecated)
  .map((i) => (i.aliases.length ? `${i.name}:${i.aliases.join(',')}` : i.name))
  .sort();
writeFileSync(
  new URL('../src/mdi-names.js', import.meta.url),
  `// Generated by scripts/mdi-names.mjs from @mdi/svg ${version}: do not edit.\n` +
    `// Material Design Icons: "name" or "name:alias,alias", without the "mdi:" prefix.\n` +
    `export const MDI_ICONS = ${JSON.stringify(icons.join(' '))};\n`,
);
console.log(`${icons.length} icons`);
